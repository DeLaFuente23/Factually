/**
 * Back-fill tool: freezes historical daily challenges into the authoritative store.
 *
 * Every date from `ARCHIVE_START` up to (and including) today was originally
 * selected by the deterministic hash in `makeChallenge()`. This script reproduces
 * those exact nine claims per date and emits the SQL to import them as permanent
 * snapshots, so the Archive and any resubmission keep validating after the switch
 * to randomised, server-generated challenges.
 *
 * Usage (writes supabase/backfill-history.sql):
 *   node scripts/backfill-history.cjs
 *
 * Then, against the linked project:
 *   supabase db push        # applies the inventory migration first
 *   psql "$DATABASE_URL" -f supabase/backfill-history.sql
 *
 * Or paste the generated SQL into the Supabase SQL editor.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ARCHIVE_START = '2026-10-13';
const library = JSON.parse(fs.readFileSync(path.join(ROOT, 'src', 'claims.json'), 'utf8'));

// Mirrors the original selection in src/game.ts. Kept verbatim so historical
// challenges reproduce byte-for-byte.
function hash(s) {
  let h = 2166136261;
  for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return h >>> 0;
}

function makeChallenge(date, lib) {
  const categories = ['FACT', 'KINDA', 'BULLSHIT'];
  const chosen = new Set();
  return [0, 1, 2].map((round) => categories.map((cat) => {
    const options = lib.filter((c) => c.category === cat);
    let seed = hash(`${date}:${round}:${cat}`);
    let pick = options[seed % options.length];
    for (let i = 0; i < options.length && chosen.has(pick.id); i++) pick = options[(seed + i + 1) % options.length];
    chosen.add(pick.id);
    return pick;
  }));
}

const today = new Date();
const todayKey = `${today.getUTCFullYear()}-${String(today.getUTCMonth() + 1).padStart(2, '0')}-${String(today.getUTCDate()).padStart(2, '0')}`;

const dates = [];
for (let d = new Date(`${ARCHIVE_START}T00:00:00Z`); d.toISOString().slice(0, 10) <= todayKey; d.setUTCDate(d.getUTCDate() + 1)) {
  dates.push(d.toISOString().slice(0, 10));
}

const known = new Set(library.map((c) => c.id));
const lines = [
  '-- Generated by scripts/backfill-history.cjs',
  `-- Freezes ${dates.length} historical challenge(s): ${ARCHIVE_START} .. ${todayKey}`,
  '-- Idempotent: inventory_import_challenge never overwrites an existing row.',
  '',
];
let problems = 0;
for (const date of dates) {
  const rounds = makeChallenge(date, library).map((round, index) => ({
    round: index + 1,
    claim_ids: round.map((claim) => claim.id),
  }));
  const ids = rounds.flatMap((r) => r.claim_ids);
  if (ids.length !== 9 || new Set(ids).size !== 9 || ids.some((id) => !known.has(id))) {
    console.error(`SKIP ${date}: invalid selection`, ids);
    problems++;
    continue;
  }
  const status = date < todayKey ? 'archived' : 'active';
  lines.push(
    `select public.inventory_import_challenge('${date}'::date, '${JSON.stringify(rounds)}'::jsonb, '${status}');`,
  );
}
lines.push('');

const out = path.join(ROOT, 'supabase', 'backfill-history.sql');
fs.writeFileSync(out, lines.join('\n'));
console.log(`dates: ${dates.length}, problems: ${problems}`);
console.log(`wrote ${path.relative(ROOT, out)}`);
console.log(`first: ${dates[0]} -> ${makeChallenge(dates[0], library).map((r) => r.map((c) => c.id).join('/')).join(' | ')}`);
console.log(`last:  ${dates[dates.length - 1]} -> ${makeChallenge(dates[dates.length - 1], library).map((r) => r.map((c) => c.id).join('/')).join(' | ')}`);
